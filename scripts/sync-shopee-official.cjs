#!/usr/bin/env node
/**
 * Syncs the Shopee client with the official Shopee Open Platform API metadata (the same JSON the public
 * documentation site renders).
 *
 *   node scripts/sync-shopee-official.cjs             # fetch (cached) + generate
 *   node scripts/sync-shopee-official.cjs --refresh   # ignore the cache and re-download
 *   node scripts/sync-shopee-official.cjs --offline   # use the cache only
 *
 * Generates, under packages/shopee-api-client:
 *   src/module/shopee/common/api-types.ts       path -> API type for every non-shop API (merchant/user/principal/public).
 *                                                Shopee signs each type with a different identity.
 *   test/fixtures/official-manifest.json        name, path, HTTP verb and type of every official API (used by tests).
 */
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const root = path.resolve(__dirname, '..');
const pkg = path.join(root, 'packages/shopee-api-client');
const cacheDir = path.join(root, '.cache/shopee-official');
const args = new Set(process.argv.slice(2));
const BASE = 'https://open.shopee.com/opservice/api/v1/doc';
const VERBS = { 1: 'POST', 2: 'GET' };
const TYPE_KEY = { Shop: 'shop', Merchant: 'merchant', User: 'user', Principal: 'principal', Public: 'public' };

async function getJson(url, cacheFile) {
  const file = path.join(cacheDir, cacheFile);
  if (!args.has('--refresh') && fs.existsSync(file)) return JSON.parse(fs.readFileSync(file, 'utf8'));
  if (args.has('--offline')) throw new Error('missing cache entry ' + cacheFile + ' (run without --offline)');
  const res = await fetch(url, { headers: { accept: 'application/json' } });
  const json = await res.json();
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, JSON.stringify(json));
  return json;
}

(async () => {
  const cds = () => 'SPC_CDS=' + crypto.randomUUID() + '&SPC_CDS_VER=2';
  const modules = (await getJson(`${BASE}/module/?version=2&${cds()}`, 'modules.json')).modules.filter((m) => m.type === 1);
  const names = modules.flatMap((m) => (m.items || []).map((i) => i.name));
  const apis = [];
  const queue = names.slice();
  await Promise.all(
    Array.from({ length: 4 }, async () => {
      while (queue.length) {
        const name = queue.shift();
        const detail = await getJson(`${BASE}/api/?${cds()}&version=2&api_name=${encodeURIComponent(name)}`, 'api/' + name.replace(/[^\w.]/g, '_') + '.json');
        if (detail && detail.path) apis.push(detail);
      }
    }),
  );
  apis.sort((a, b) => a.path.localeCompare(b.path));

  const nonShop = apis.filter((a) => TYPE_KEY[a.api_type] && TYPE_KEY[a.api_type] !== 'shop');
  const entries = nonShop.map((a) => `  '${a.path}': '${TYPE_KEY[a.api_type]}',\n`).join('');
  fs.writeFileSync(
    path.join(pkg, 'src/module/shopee/common/api-types.ts'),
    `// Generated by scripts/sync-shopee-official.cjs from the official Shopee Open Platform API metadata. Do not edit by hand.

/**
 * Shopee signs and authenticates each API with a different identity, depending on its type:
 *
 *   shop       partner_id + path + timestamp + access_token + shop_id        (the default)
 *   merchant   partner_id + path + timestamp + access_token + merchant_id
 *   user       partner_id + path + timestamp + access_token + user_id
 *   principal  partner_id + path + timestamp + access_token + principal_id
 *   public     partner_id + path + timestamp                                 (no access token)
 */
export type ShopeeApiType = 'shop' | 'merchant' | 'user' | 'principal' | 'public';

/** Full API path -> type, for every API that is NOT a plain shop API. Anything absent is a shop API. */
export const SHOPEE_API_TYPES: Readonly<Record<string, ShopeeApiType>> = {
${entries}};
`,
  );

  const manifest = apis.map((a) => ({
    name: a.api_name,
    path: a.path,
    verb: VERBS[a.method] || 'UNKNOWN(' + a.method + ')',
    type: TYPE_KEY[a.api_type] || a.api_type,
  }));
  fs.mkdirSync(path.join(pkg, 'test/fixtures'), { recursive: true });
  fs.writeFileSync(path.join(pkg, 'test/fixtures/official-manifest.json'), JSON.stringify(manifest, null, 2) + '\n');

  const byType = {};
  manifest.forEach((m) => (byType[m.type] = (byType[m.type] || 0) + 1));
  console.log('official APIs:', apis.length, JSON.stringify(byType));
  console.log('api-types.ts entries:', nonShop.length);
  // ---- Generate the official APIs that the client does not expose yet -------------------------------------------
  generateMissing(apis);
})().catch((error) => {
  console.error(error);
  process.exit(1);
});

/** Namespaces for APIs that are in the official reference but not (yet) in the hand-written client. */
const MISSING_NAMESPACES = [
  { key: 'buybox', file: 'buybox', cls: 'Buybox', match: (a) => /^v2\.buybox\./.test(a.api_name), doc: 'v2.buybox.*' },
  { key: 'businessInsights', file: 'business-insights', cls: 'BusinessInsights', match: (a) => /^v2\.business_insights\./.test(a.api_name), doc: 'v2.business_insights.*' },
  { key: 'productSsp', file: 'product-ssp', cls: 'ProductSsp', match: (a) => /^v2\.product\..*ssp/.test(a.api_name), doc: 'v2.product.*ssp* (Standardized Shop Product)' },
];

function implementedPaths() {
  const src = path.join(pkg, 'src/module/shopee');
  const generated = new Set(MISSING_NAMESPACES.flatMap((n) => [`api/${n.file}.api.ts`, `submodules/${n.file}.submodule.ts`]));
  const found = new Set();
  const walk = (dir) => {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) { if (entry.name !== 'dto') walk(full); continue; }
      if (!entry.name.endsWith('.ts') || generated.has(path.relative(src, full))) continue;
      const text = fs.readFileSync(full, 'utf8');
      for (const m of text.matchAll(/['"`](\/api\/v2\/[A-Za-z0-9_/]+)['"`]/g)) found.add(m[1]);
      for (const m of text.matchAll(/callShopee(?:Public)?Api<[^>]*>\(\s*['"`](\/[A-Za-z0-9_/]+)['"`]/g)) found.add('/api/v2' + m[1]);
      for (const m of text.matchAll(/signRequest\(\s*['"`](\/[A-Za-z0-9_/]+)['"`]/g)) found.add('/api/v2' + m[1]);
    }
  };
  walk(src);
  return found;
}

const words = (s) => s.replace(/[^A-Za-z0-9]+/g, ' ').trim().split(/\s+/).filter(Boolean);
const pascal = (s) => words(s).map((w) => w.charAt(0).toUpperCase() + w.slice(1)).join('');
const camel = (s) => { const p = pascal(s); return p.charAt(0).toLowerCase() + p.slice(1); };
const plain = (html) => String(html || '').replace(/<[^>]+>/g, ' ').replace(/&nbsp;/g, ' ').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&amp;/g, '&').replace(/\s+/g, ' ').trim();
const safeKey = (n) => (/^[A-Za-z_$][\w$]*$/.test(n) ? n : JSON.stringify(n));
const docLine = (text, indent) => (text ? indent + '/** ' + String(text).replace(/\*\//g, '*\\/') + ' */\n' : '');

function tsType(node, indent, optionalAll) {
  const t = String(node.type || '').toLowerCase();
  const obj = () => (node.children && node.children.length ? '{\n' + fields(node.children, indent + '  ', optionalAll) + indent + '}' : 'Record<string, unknown>');
  if (t === 'string') return 'string';
  if (['int', 'int32', 'int64', 'float', 'double', 'number', 'long', 'timestamp'].includes(t)) return 'number';
  if (t === 'bool' || t === 'boolean') return 'boolean';
  if (t === 'object') return obj();
  if (t === 'object[]') return 'Array<' + obj() + '>';
  if (t === 'string[]') return 'string[]';
  if (/^(int|int32|int64|float|double|number|long|timestamp)\[\]$/.test(t)) return 'number[]';
  if (t === 'bool[]' || t === 'boolean[]') return 'boolean[]';
  return 'unknown';
}
function fields(nodes, indent, optionalAll) {
  return nodes
    .map((n) => docLine(plain(n.description), indent) + indent + safeKey(n.name) + (optionalAll || String(n.required) !== 'True' ? '?' : '') + ': ' + tsType(n, indent, optionalAll) + ';\n')
    .join('');
}

function generateMissing(apis) {
  const implemented = implementedPaths();
  const missing = apis.filter((a) => !implemented.has(a.path));
  const unassigned = missing.filter((a) => !MISSING_NAMESPACES.some((n) => n.match(a)));
  if (unassigned.length) console.log('official APIs without a namespace (not generated): ' + unassigned.map((a) => a.api_name).join(', '));
  const header = '// Generated by scripts/sync-shopee-official.cjs from the official Shopee Open Platform API metadata. Do not edit by hand.\n\n';
  const src = path.join(pkg, 'src/module/shopee');
  let total = 0;
  for (const ns of MISSING_NAMESPACES) {
    const list = missing.filter((a) => ns.match(a));
    if (!list.length) continue;
    const models = list.map((a) => {
      const params = JSON.parse(a.params);
      const method = camel(a.path.split('/').pop());
      const request = (params.request_params || []).filter((p) => !['access_token', 'partner_id', 'shop_id', 'sign', 'timestamp'].includes(p.name));
      const response = ((params.response_params || []).find((p) => p.name === 'response') || {}).children || [];
      return { a, method, T: 'Shopee' + pascal(method), request, response, verb: a.method === 2 ? 'GET' : 'POST', desc: plain((JSON.parse(a.define || '{}') || {}).content || '') };
    });
    let req = header; let res = header + "import { ShopeeResponseCommon } from './config.response';\n\n";
    for (const m of models) {
      if (m.request.length) req += docLine(m.a.api_name + ' - ' + m.desc, '') + `export interface ${m.T}Request {\n${fields(m.request, '  ', false)}}\n\n`;
      res += `export interface ${m.T}ResponseData {\n${fields(m.response, '  ', true)}}\n\n` + docLine(m.a.api_name, '') + `export type ${m.T}Response = ShopeeResponseCommon<${m.T}ResponseData>;\n\n`;
    }
    if (!/export /.test(req)) req += 'export {};\n';
    const reqTypes = models.filter((m) => m.request.length).map((m) => m.T + 'Request');
    const resTypes = models.map((m) => m.T + 'Response');
    let api = header + "import { ShopeeConfig } from '../dto/request/config.request';\nimport * as ShopeeHelper from '../common/helper';\n";
    if (reqTypes.length) api += `import type { ${reqTypes.join(', ')} } from '../dto/request/${ns.file}.request';\n`;
    api += `import type { ${resTypes.join(', ')} } from '../dto/response/${ns.file}.response';\n\n`;
    for (const m of models) {
      const hasReq = m.request.length > 0;
      const requiredReq = m.request.some((p) => String(p.required) === 'True');
      const decl = hasReq ? (requiredReq ? `params: ${m.T}Request, ` : `params: ${m.T}Request = {}, `) : '';
      api += `/**\n * ${m.a.api_name}\n *\n * ${m.desc || m.a.api_name}\n *\n * Endpoint: \`${m.verb} ${m.a.path}\`\n * @see https://open.shopee.com/documents/v2/${encodeURIComponent(m.a.api_name)}?module=${m.a.module_id}&type=1\n */\n`;
      api += `export async function ${m.method}(${decl}config: ShopeeConfig): Promise<${m.T}Response> {\n  return ShopeeHelper.callShopeeApi<${m.T}Response>('${m.a.path.replace('/api/v2', '')}', config, {\n    method: '${m.verb}',\n    params: ${hasReq ? 'params as unknown as Record<string, string | number | boolean | Array<string | number | boolean> | undefined>' : 'undefined'},\n    context: '${m.method}',\n  });\n}\n\n`;
    }
    let sub = header + "import { ShopeeConfig } from '../dto/request/config.request';\n";
    sub += `import { ${models.map((m) => m.method).join(', ')} } from '../api/${ns.file}.api';\n`;
    if (reqTypes.length) sub += `import type { ${reqTypes.join(', ')} } from '../dto/request/${ns.file}.request';\n`;
    sub += `import type { ${resTypes.join(', ')} } from '../dto/response/${ns.file}.response';\n\n`;
    sub += `/**\n * Shopee \`${ns.doc}\` API namespace.\n *\n * Access via \`shopee.${ns.key}.<method>()\` on a \`ShopeeModule\` instance.\n */\nexport class Shopee${ns.cls} {\n  constructor(private config: ShopeeConfig) {}\n\n`;
    for (const m of models) {
      const hasReq = m.request.length > 0;
      const requiredReq = m.request.some((p) => String(p.required) === 'True');
      const decl = hasReq ? (requiredReq ? `params: ${m.T}Request` : `params: ${m.T}Request = {}`) : '';
      sub += `  async ${m.method}(${decl}): Promise<${m.T}Response> {\n    return await ${m.method}(${hasReq ? 'params, ' : ''}this.config);\n  }\n\n`;
    }
    sub = sub.replace(/\n\n$/, '\n') + '}\n';
    fs.writeFileSync(path.join(src, 'dto/request', ns.file + '.request.ts'), req);
    fs.writeFileSync(path.join(src, 'dto/response', ns.file + '.response.ts'), res);
    fs.writeFileSync(path.join(src, 'api', ns.file + '.api.ts'), api.replace(/\n\n$/, '\n'));
    fs.writeFileSync(path.join(src, 'submodules', ns.file + '.submodule.ts'), sub);
    console.log('  generated shopee.' + ns.key + ': ' + models.map((m) => m.method).join(', '));
    total += models.length;
  }
  console.log('generated ' + total + ' methods for official APIs missing from the client');
}
